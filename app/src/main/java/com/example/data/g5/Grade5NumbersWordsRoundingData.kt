object Grade5NumbersWordsRoundingData {

  private fun roundOff(n: Int, place: String): Int {
    val unit = if (place.lowercase().startsWith("ten")) 10_000 else 1_000
    val rem = n % unit
    return if (rem >= unit / 2) n - rem + unit else n - rem
  }

  private fun rnd(item: Int, n: Int, place: String) = MathProblem.RoundingProblem(
    itemNumber = item,
    number = n,
    targetPlace = place,
    answer = roundOff(n, place),
    hint = "Check the digit immediately right of the $place place: 5+ rounds up, 0–4 keeps it.",
  )

  private fun ord(item: Int, nums: List<Int>, inc: Boolean) = MathProblem.OrderNumbersProblem(
    itemNumber = item,
    numbers = nums,
    increasing = inc,
    expectedOrder = if (inc) nums.sorted() else nums.sortedDescending(),
    hint = if (inc) "Increasing: start from the smallest number to the largest." else "Decreasing: start from the largest number to the smallest.",
  )

  private fun cmp(item: Int, leftDisp: String, leftVal: Int, rightDisp: String, rightVal: Int, leftWords: Boolean): MathProblem.CompareWholeNumbersProblem {
    val sym = when {
      leftVal < rightVal -> "<"
      leftVal > rightVal -> ">"
      else -> "="
    }
    return MathProblem.CompareWholeNumbersProblem(
      itemNumber = item,
      leftDisplay = leftDisp,
      leftValue = leftVal,
      rightDisplay = rightDisp,
      rightValue = rightVal,
      leftIsWords = leftWords,
      answerSymbol = sym,
      hint = "Convert the words to digits mentally, then compare from left to right.",
    )
  }

